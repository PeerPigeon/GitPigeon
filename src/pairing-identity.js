import { createHash, createHmac, randomBytes, timingSafeEqual } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const KEY_FILE = 'pairing-key.json';

/**
 * Six digits derived from the watcher's own public key — the key unsea
 * encrypts the pairing grant to.
 *
 * This deliberately does not mix in the browser's key. A per-pair code cannot
 * exist until a browser asks, which meant `install` had nothing to print and
 * sat waiting instead. The watcher owns its identity, so it can state its code
 * the moment it is installed, and every browser that discovers that watcher
 * derives the same digits from the key PeerPigeon found for it. Confirming
 * them still proves the grant is going to the machine in front of you.
 */
export function pairingCode(watcherPublicKey) {
  const watcher = String(watcherPublicKey ?? '');
  if (!watcher) throw new Error('A pairing code requires the watcher public key');
  const digest = createHash('sha256')
    .update('gitpigeon:pair-code:v4\0')
    .update(watcher)
    .digest();
  return String(digest.readUInt32BE(0) % 1_000_000).padStart(6, '0');
}

function validKeyPair(value) {
  if (!value || typeof value !== 'object') return null;
  for (const field of ['pub', 'priv', 'epub', 'epriv']) {
    if (typeof value[field] !== 'string' || !value[field]) return null;
  }
  return { pub: value.pub, priv: value.priv, epub: value.epub, epriv: value.epriv };
}

/**
 * The watcher's stable pairing identity, generated by unsea — PeerPigeon's own
 * cryptography — and reused across restarts. A fresh key each start would
 * change the code every time the service bounced.
 */
export async function loadPairingKeyPair(root) {
  const file = path.join(root, KEY_FILE);
  try {
    const stored = validKeyPair(JSON.parse(await readFile(file, 'utf8')));
    if (stored) return stored;
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  const { generateRandomPair } = await import('unsea');
  const created = validKeyPair(await generateRandomPair());
  if (!created) throw new Error('unsea returned an unusable pairing key pair');
  await mkdir(root, { recursive: true });
  await writeFile(file, `${JSON.stringify(created, null, 2)}\n`, { mode: 0o600 });
  return created;
}

const WINDOW_FILE = 'pairing-window.json';
export const PAIRING_WINDOW_MS = 10 * 60_000;

/**
 * The background service hands this machine's index capability to a browser
 * ONLY while a pairing window is open, and a window is opened only by someone
 * at this machine running a pairing command.
 *
 * It used to offer to every browser that announced itself, always. The
 * approval mesh is one public network, the announcement is a plain broadcast
 * anyone can make, and the six digits are derived from a public key — so the
 * "approve only if the code matches" check ran in the REQUESTER's browser,
 * after the capability had already arrived there. Anyone who opened the
 * dashboard received the index secret of every watcher online: every
 * repository on the index, and a terminal on every machine.
 */
const PHRASE_ALPHABET = 'ABCDEFGHJKMNPQRSTVWXYZ23456789';
const PHRASE_GROUPS = 3;
const PHRASE_GROUP_LENGTH = 4;
export const PAIRING_MAX_FAILURES = 5;

/**
 * Twelve characters from a thirty-symbol alphabet: a little under sixty
 * bits, shown only in this machine's terminal, good for one window and one
 * pairing. Short enough to read to someone; far too long to guess in five
 * tries or to search before the window shuts.
 */
export function createPairingPhrase() {
  const symbols = [];
  while (symbols.length < PHRASE_GROUPS * PHRASE_GROUP_LENGTH) {
    // Rejection sampling: 240 is the largest multiple of the alphabet size
    // that fits a byte, so every symbol stays equally likely.
    for (const value of randomBytes(32)) {
      if (value < 240 && symbols.length < PHRASE_GROUPS * PHRASE_GROUP_LENGTH) {
        symbols.push(PHRASE_ALPHABET[value % PHRASE_ALPHABET.length]);
      }
    }
  }
  return Array.from({ length: PHRASE_GROUPS }, (_, group) => (
    symbols.slice(group * PHRASE_GROUP_LENGTH, (group + 1) * PHRASE_GROUP_LENGTH).join('')
  )).join('-');
}

/** Typed by a person: case, spaces and dashes are not part of the secret. */
export function normalizePairingPhrase(value) {
  return String(value ?? '').toUpperCase().replace(/[^A-Z0-9]/g, '');
}

/**
 * What a requester sends instead of the phrase: bound to its own request and
 * to the key the answer will be sealed to, so a proof copied off the mesh is
 * worth nothing to anyone else.
 */
export function pairingProof(phrase, { requestId, epub }) {
  return createHmac('sha256', normalizePairingPhrase(phrase))
    .update('gitpigeon-pairing-proof/1\0')
    .update(String(requestId))
    .update('\0')
    .update(String(epub))
    .digest('hex');
}

/**
 * One phrase, several statements, each under its own label so none can be
 * replayed as another:
 *   proof    — a browser asking this machine for its index;
 *   answer   — this machine answering that browser;
 *   announce — this machine saying "I am the one showing that phrase", so a
 *              dashboard lists it ONLY for whoever typed the phrase;
 *   grant    — a dashboard handing this machine an index to join.
 */
export function pairingMac(purpose, phrase, { requestId, epub }) {
  return createHmac('sha256', normalizePairingPhrase(phrase))
    .update(`gitpigeon-pairing-${purpose}/1\0`)
    .update(String(requestId))
    .update('\0')
    .update(String(epub))
    .digest('hex');
}

/** This machine's statement for a purpose, from the open window; null when shut. */
export async function pairingMacFor(root, purpose, request, now = Date.now()) {
  try {
    const state = JSON.parse(await readFile(path.join(root, WINDOW_FILE), 'utf8'));
    const until = Date.parse(String(state?.until ?? ''));
    if (!Number.isFinite(until) || until <= now || typeof state.phrase !== 'string') return null;
    return pairingMac(purpose, state.phrase, request);
  } catch {
    return null;
  }
}

/**
 * Whether a statement made TO this machine proves the open phrase. Wrong
 * ones count against the window exactly as wrong browser proofs do.
 */
export async function verifyPairingMac(root, purpose, { requestId, epub, proof }, now = Date.now()) {
  const file = path.join(root, WINDOW_FILE);
  let state;
  try { state = JSON.parse(await readFile(file, 'utf8')); } catch { return false; }
  const until = Date.parse(String(state?.until ?? ''));
  if (!Number.isFinite(until) || until <= now || until - now > PAIRING_WINDOW_MS + 1_000) return false;
  if (typeof state.phrase !== 'string' || normalizePairingPhrase(state.phrase).length < 12) return false;
  if (!epub || !requestId || !/^[0-9a-f]{64}$/.test(String(proof ?? ''))) return false;
  const expected = Buffer.from(pairingMac(purpose, state.phrase, { requestId, epub }), 'hex');
  const given = Buffer.from(String(proof), 'hex');
  if (given.length === expected.length && timingSafeEqual(given, expected)) return true;
  const failures = (Number(state.failures) || 0) + 1;
  if (failures >= PAIRING_MAX_FAILURES) await closePairingWindow(root).catch(() => {});
  else await writeFile(file, `${JSON.stringify({ ...state, failures })}\n`, { mode: 0o600 }).catch(() => {});
  return false;
}

/**
 * The watcher's half of the handshake. A browser that proved the phrase is
 * answered with proof that THIS machine knows it too — so the browser can
 * take the answer without asking anyone to compare digits, and an answer
 * from any other machine on the mesh (which sees the request and the key to
 * seal to, like everyone) is recognisably not the one that was asked.
 */
export function pairingAnswer(phrase, { requestId, epub }) {
  return createHmac('sha256', normalizePairingPhrase(phrase))
    .update('gitpigeon-pairing-answer/1\0')
    .update(String(requestId))
    .update('\0')
    .update(String(epub))
    .digest('hex');
}

/** The answer for a request, from the open window's phrase; null when shut. */
export async function pairingAnswerFor(root, request, now = Date.now()) {
  try {
    const state = JSON.parse(await readFile(path.join(root, WINDOW_FILE), 'utf8'));
    const until = Date.parse(String(state?.until ?? ''));
    if (!Number.isFinite(until) || until <= now || typeof state.phrase !== 'string') return null;
    return pairingAnswer(state.phrase, request);
  } catch {
    return null;
  }
}

export async function openPairingWindow(root, { ms = PAIRING_WINDOW_MS, now = Date.now() } = {}) {
  await mkdir(root, { recursive: true });
  const until = new Date(now + ms).toISOString();
  const phrase = createPairingPhrase();
  await writeFile(path.join(root, WINDOW_FILE), `${JSON.stringify({ until, phrase, failures: 0 })}\n`, { mode: 0o600 });
  return { until, phrase };
}

/**
 * Whether a request proves knowledge of this machine's open phrase. A wrong
 * proof counts against the window; enough of them shut it, so the phrase
 * cannot be searched online however fast requests arrive.
 */
