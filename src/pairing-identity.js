import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const KEY_FILE = 'pairing-key.json';

/**
 * Six digits derived from the watcher's own public key — the key unsea
 * encrypts the pairing grant to.
 *
 * This deliberately does not mix in the browser's key. A per-pair code cannot
 * exist until a browser asks, which meant `install` had nothing to print and
 * sat waiting instead. The watcher owns its identity, so it can state its code
 * the moment it is installed, and every browser that discovers that watcher
 * derives the same digits from the key PeerPigeon found for it. Confirming
 * them still proves the grant is going to the machine in front of you.
 */
export function pairingCode(watcherPublicKey) {
  const watcher = String(watcherPublicKey ?? '');
  if (!watcher) throw new Error('A pairing code requires the watcher public key');
  const digest = createHash('sha256')
    .update('gitpigeon:pair-code:v4\0')
    .update(watcher)
    .digest();
  return String(digest.readUInt32BE(0) % 1_000_000).padStart(6, '0');
}

function validKeyPair(value) {
  if (!value || typeof value !== 'object') return null;
  for (const field of ['pub', 'priv', 'epub', 'epriv']) {
    if (typeof value[field] !== 'string' || !value[field]) return null;
  }
  return { pub: value.pub, priv: value.priv, epub: value.epub, epriv: value.epriv };
}

/**
 * The watcher's stable pairing identity, generated by unsea — PeerPigeon's own
 * cryptography — and reused across restarts. A fresh key each start would
 * change the code every time the service bounced.
 */
export async function loadPairingKeyPair(root) {
  const file = path.join(root, KEY_FILE);
  try {
    const stored = validKeyPair(JSON.parse(await readFile(file, 'utf8')));
    if (stored) return stored;
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  const { generateRandomPair } = await import('unsea');
  const created = validKeyPair(await generateRandomPair());
  if (!created) throw new Error('unsea returned an unusable pairing key pair');
  await mkdir(root, { recursive: true });
  await writeFile(file, `${JSON.stringify(created, null, 2)}\n`, { mode: 0o600 });
  return created;
}

const WINDOW_FILE = 'pairing-window.json';
export const PAIRING_WINDOW_MS = 10 * 60_000;

/**
 * The background service hands this machine's index capability to a browser
 * ONLY while a pairing window is open, and a window is opened only by someone
 * at this machine running a pairing command.
 *
 * It used to offer to every browser that announced itself, always. The
 * approval mesh is one public network, the announcement is a plain broadcast
 * anyone can make, and the six digits are derived from a public key — so the
 * "approve only if the code matches" check ran in the REQUESTER's browser,
 * after the capability had already arrived there. Anyone who opened the
 * dashboard received the index secret of every watcher online: every
 * repository on the index, and a terminal on every machine.
 */
export async function openPairingWindow(root, { ms = PAIRING_WINDOW_MS, now = Date.now() } = {}) {
  await mkdir(root, { recursive: true });
  const until = new Date(now + ms).toISOString();
  await writeFile(path.join(root, WINDOW_FILE), `${JSON.stringify({ until })}\n`, { mode: 0o600 });
  return until;
}

export async function closePairingWindow(root) {
  const { rm } = await import('node:fs/promises');
  await rm(path.join(root, WINDOW_FILE), { force: true });
}

export async function pairingWindowOpen(root, now = Date.now()) {
  try {
    const until = Date.parse(String(JSON.parse(await readFile(path.join(root, WINDOW_FILE), 'utf8')).until ?? ''));
    return Number.isFinite(until) && until > now && until - now <= PAIRING_WINDOW_MS + 1_000;
  } catch {
    return false;
  }
}

/** The code this machine shows, without touching the network. */
export async function localPairingCode(root) {
  return pairingCode((await loadPairingKeyPair(root)).pub);
}
